function hash(text) {
    let value = 0;
    for (let i = 0; i < text.length; i += 1) {
        value = (value * 31 + text.charCodeAt(i)) % 1000000007;
    }
    return value;
}

// 由 openid 派生的本地种子：稳定、不可逆，避免把原文传进词库模块或日志。
function seed(text) {
    return String(hash(String(text || '')));
}

function levelIndex(points) {
    const total = Math.max(0, Number(points) || 0);
    let index = 0;
    for (let i = 0; i < LEVELS.length; i += 1) {
        if (total >= LEVELS[i].min) index = i;
    }
    return index;
}

// 当前等级的整套主题：名称 + 文字色 + 浅色底。
function themeOf(points) {
    return LEVELS[levelIndex(points)];
}

function levelOf(points) {
    return themeOf(points).name;
}

// 用 UTC 把 yyyy-MM-dd 折算成天数，设备时区或夏令时不会改变同一天的取值。
function dayIndex(dateText) {
    const parts = String(dateText || '').split('-');
    const year = Number(parts[0]);
    const month = Number(parts[1]);
    const day = Number(parts[2]);
    if (!year || !month || !day) return 0;
    return Math.floor(Date.UTC(year, month - 1, day) / 86400000);
}

function pick(dateText, points, userKey) {
    // 万一以后只加了等级没补词库，也不至于取到 undefined 导致页面报错。
    const group = WORDS[Math.min(levelIndex(points), WORDS.length - 1)];
    const size = group.length;
    // 每人一个固定相位：同一天不同用户落在不同句子；
    // 同一用户每过一天索引 +1，12 句轮完一圈才会重复，不会连着两天读同一句。
    const offset = hash(String(userKey || '')) % size;
    const index = ((dayIndex(dateText) + offset) % size + size) % size;
    return group[index];
}

